const dicts: Record<Lang, Dict> = { en, fa, ar, tr, es };

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  t: (k: string, vars?: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
};
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("iranapi.lang") as Lang | null;
      if (saved && dicts[saved]) return saved;
      const nav = (typeof navigator !== "undefined" && navigator.language?.slice(0, 2)) as Lang | undefined;
      if (nav && dicts[nav]) return nav;
    } catch {
      // Ignore unavailable storage (private mode, SSR-like shells).
    }
    return "en";
  });

  useLayoutEffect(() => {
    const entry = LANGS.find((l) => l.code === lang)!;
    document.documentElement.lang = lang;
    document.documentElement.dir = entry.dir;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("iranapi.lang", l); } catch {
      // Language switch still works for current session without persistence.
    }
  }, []);

  const t = useCallback(
    (k: string, vars?: Record<string, string | number>) => {
      let s = dicts[lang][k] ?? dicts.en[k] ?? k;
      if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replace(`{${vk}}`, String(vv));
      return s;
    },
    [lang],
  );
  const dir = LANGS.find((l) => l.code === lang)!.dir;

  return <I18nContext.Provider value={{ lang, dir, t, setLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be inside I18nProvider");
  return ctx;
}
